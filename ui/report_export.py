import streamlit as st

from ppt.create_api_ppt import create_api_meta_report_ppt
from ui.report_config import get_report_view_snapshot


def _render_one_export(
    report_number,
    ad_row,
    report_period,
    period_result,
):
    if (
        ad_row is None
        or report_period is None
        or period_result is None
    ):
        return

    visibility = get_report_view_snapshot()

    st.markdown(f"**レポート{report_number}**")

    # Generate only after the click, without delaying the report screen.
    if st.button(
        "PPTをダウンロード",
        key=f"download_api_ppt_{report_number}",
        use_container_width=True,
    ):
        import base64
        import json

        import streamlit.components.v1 as components

        with st.spinner("PowerPointを作成しています..."):
            path = create_api_meta_report_ppt(
                ad_row=ad_row,
                report_period=report_period,
                period_result=period_result,
                visibility=visibility,
                report_key=f"report_{report_number}",
            )
            encoded = base64.b64encode(path.read_bytes()).decode("ascii")
            filename = json.dumps(path.name, ensure_ascii=False)

        # Trigger the browser download from the freshly generated bytes.
        # No session-state PPT cache: a previous facility cannot be reused.
        components.html(
            f"""
            <script>
            const binary = atob("{encoded}");
            const bytes = new Uint8Array(binary.length);
            for (let i = 0; i < binary.length; i++) {{
                bytes[i] = binary.charCodeAt(i);
            }}
            const blob = new Blob([bytes], {{
                type: "application/vnd.openxmlformats-officedocument.presentationml.presentation"
            }});
            const url = URL.createObjectURL(blob);
            const link = document.createElement("a");
            link.href = url;
            link.download = {filename};
            document.body.appendChild(link);
            link.click();
            link.remove();
            setTimeout(() => URL.revokeObjectURL(url), 10000);
            </script>
            """,
            height=0,
        )


def render_api_ppt_export_controls(
    report_1_ad,
    report_1_period,
    report_1_period_result,
    report_2_ad=None,
    report_2_period=None,
    report_2_period_result=None,
):
    st.divider()
    st.subheader("PowerPoint出力")

    if (
        report_2_ad is not None
        and report_2_period is not None
        and report_2_period_result is not None
    ):
        left, right = st.columns(2)

        with left:
            _render_one_export(
                1,
                report_1_ad,
                report_1_period,
                report_1_period_result,
            )

        with right:
            _render_one_export(
                2,
                report_2_ad,
                report_2_period,
                report_2_period_result,
            )
    else:
        _render_one_export(
            1,
            report_1_ad,
            report_1_period,
            report_1_period_result,
        )
